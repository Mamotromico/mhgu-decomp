#!/usr/bin/env python3
"""Generate the committed symbol ledger from the Ghidra inventory export.

The inventory export (``tools/ghidra/InventoryExport.java`` driven by
``tools/ghidra/inventory.sh`` → ``baserom/work/inventory/``) is a *draft*: it proposes cut
points but never decides identity, boundaries, names, or the progress denominator. This tool
promotes that draft into the **committed, typed symbol ledger** — the single source of truth
every downstream mechanism (build inputs, the shared "matched" predicate, the denominator)
draws from. See ``docs/architecture.md`` → *Symbol ledger*.

It is deliberately a **near-identity mapping** of the export (see *Ledger & export format*):
a diff of the two shows exactly where a human overrode the draft.

Transformations applied
-----------------------
* keep only ``class == content`` cut points (loader-synthesised ``metadata`` blocks are
  regenerated by the link, never reconstructed from source, so they are excluded);
* rename generated placeholders to ``func_<addr>`` / ``D_<addr>``; reproduce discovered
  names (the 12 ``IMPORTED`` symbols) verbatim;
* partition each block at its cut points: an entry's ``size`` is the distance to the next cut
  point (the last entry uses the block end from ``inventory.blocks.tsv``), so addressed ranges
  are disjoint *and* tile the block — Ghidra's body *span* neither tiles nor stays disjoint for
  non-contiguous bodies (see ``partition_sizes``);
* materialise ``content`` gaps as ``D_<addr>`` data entries, so the denominator is complete;
* append externals (parsed from ``.dynsym``) as ``kind == external``;
* stamp the initial status axes (``verify=none`` / ``review=generated`` /
  ``enroll=rombytes``) and the identity attributes (``guess=0``).

Single module
-------------
Everything is seeded as one module, ``main``. The image has no overlays, so a single
``(module, addr)`` namespace is correct; modules stay a ledger column and can be split later
by editing it, never by renaming files.

Frozen seed, not a regenerator
-------------------------------
The committed ledger is **hand-owned**: it is seeded once from the export and carries
authored state (renamed ``name``/``group``, and the ``verify``/``review``/``enroll``/
``guess`` status axes) that a regeneration must never destroy. So this tool **refuses to
overwrite an existing ledger** unless ``--force`` is passed, and it deliberately has no
``--check``: re-seeding is a rare, deliberate, reviewable event, not a CI routine. The CI
gate is the invariant validator ``tools/ledger/validate.py`` instead.

Usage::

    python3 tools/ledger/gen_ledger.py                 # seed a fresh ledger (errors if it exists)
    python3 tools/ledger/gen_ledger.py --force         # overwrite an existing ledger (deliberate)
    python3 tools/ledger/gen_ledger.py --in-dir DIR --out FILE --module NAME
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path

from ledgerlib import LEDGER_COLUMNS, STATUS_DEFAULTS

REPO = Path(__file__).resolve().parents[2]
DEFAULT_IN_DIR = REPO / "baserom" / "work" / "inventory"
DEFAULT_OUT = REPO / "config" / "main" / "ledger.tsv"


def ledger_name(kind: str, addr: str, raw: str, name_class: str) -> str:
    """Promote a draft name to a ledger identity.

    Discovered names are reproduced verbatim (the mangling is a correctness check, not an
    organizer). Generated placeholders become address-encoded: ``func_<addr>`` for code,
    ``D_<addr>`` for data. The Ghidra raw name is provenance only and never enters the ledger
    (see architecture.md → *Symbol & data naming*).
    """
    if name_class == "discovered":
        return raw
    return f"func_{addr}" if kind == "function" else f"D_{addr}"


def read_tsv(path: Path) -> list[dict]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def read_block_extents(in_dir: Path) -> dict[str, tuple[int, int]]:
    """``block -> (start, end)`` for content blocks, from ``inventory.blocks.tsv``.

    Bounds the last cut point in a block and lets a block's *head* be closed too (see
    ``fill_block_heads``). Absent file -> empty map (the last entry then keeps its draft
    size, and the caller warns).
    """
    path = in_dir / "inventory.blocks.tsv"
    if not path.exists():
        return {}
    extents: dict[str, tuple[int, int]] = {}
    for r in read_tsv(path):
        if r["class"] != "content":
            continue
        start = int(r["addr"], 16)
        extents[r["block"]] = (start, start + int(r["size"]))
    return extents


def build_entries(in_dir: Path, module: str) -> tuple[list[dict], dict]:
    """Build ledger rows from the three manifest-relevant export files."""
    entries: list[dict] = []
    stats = {"content_cut": 0, "gaps": 0, "externals": 0, "metadata_skipped": 0}

    # --- cut points: content symbols only -------------------------------------------------
    for r in read_tsv(in_dir / "inventory.tsv"):
        if r["class"] != "content":
            stats["metadata_skipped"] += 1
            continue
        kind, addr = r["kind"], r["addr"]
        name = ledger_name(kind, addr, r["name"], r["name_class"])
        entries.append(
            {
                "module": module,
                "addr": addr,
                "kind": kind,
                "name": name,
                "block": r["block"],
                "group": name,
                "size": r["size"],
                "name_class": r["name_class"],
                "bind": "",
                "guess": "0",
                **STATUS_DEFAULTS,
            }
        )
        stats["content_cut"] += 1

    # --- gaps: uncovered initialized content bytes → D_<addr> data blobs ------------------
    for r in read_tsv(in_dir / "inventory.gaps.tsv"):
        if r["class"] != "content":
            stats["metadata_skipped"] += 1
            continue
        addr = r["addr"]
        name = f"D_{addr}"
        entries.append(
            {
                "module": module,
                "addr": addr,
                "kind": "data",
                "name": name,
                "block": r["block"],
                "group": name,
                "size": r["size"],
                "name_class": "generated",
                "bind": "",
                "guess": "0",
                **STATUS_DEFAULTS,
            }
        )
        stats["gaps"] += 1

    # --- externals: first-class kind, no address ------------------------------------------
    for r in read_tsv(in_dir / "inventory.externals.tsv"):
        entries.append(
            {
                "module": module,
                "addr": "",
                "kind": "external",
                "name": r["name"],
                "block": "",
                "group": "",
                "size": "",
                "name_class": "discovered",
                "bind": r["bind"],
                "guess": "0",
                "verify": "none",
                "review": "generated",
                "enroll": "",
            }
        )
        stats["externals"] += 1

    return entries, stats


def fill_block_heads(entries: list[dict], extents: dict[str, tuple[int, int]],
                     module: str) -> int:
    """Materialise any unrepresented head of a content block as a ``D_<addr>`` blob.

    The gaps pass only covers *initialized* blocks, so a block whose first symbol does not
    sit at the block start (``.bss``: 0x6184b000 but first symbol 0x6184b05c) leaves its
    head untilled. Closing it here makes every content block a complete partition from the
    block start — no separate export change needed (``partition_sizes`` bounds the tail).
    """
    per_block: dict[str, list[dict]] = {}
    for e in entries:
        if e["kind"] != "external":
            per_block.setdefault(e["block"], []).append(e)
    filled = 0
    for block, (start, _end) in extents.items():
        rows = per_block.get(block)
        if not rows:
            continue
        first = min(rows, key=lambda e: int(e["addr"], 16))
        gap = int(first["addr"], 16) - start
        if gap <= 0:
            continue
        addr = f"{start:08x}"
        name = f"D_{addr}"
        entries.append(
            {
                "module": module,
                "addr": addr,
                "kind": "data",
                "name": name,
                "block": block,
                "group": name,
                "size": str(gap),
                "name_class": "generated",
                "bind": "",
                "guess": "0",
                **STATUS_DEFAULTS,
            }
        )
        filled += 1
    return filled


def partition_sizes(entries: list[dict], block_ends: dict[str, int]) -> int:
    """Partition each block at its cut points: ``size = next_cut - addr``.

    Ghidra's reported length is the *span* of a function body between its first and last
    instruction. For a non-contiguous body the span over-covers any function that begins in
    the gap (904/906 draft overlaps in the first export), and the gap pass — which excludes
    bytes inside a body's overall span — leaves the interior holes untilled (2.7 MB of
    unclaimed ``.text``). Both are the same defect: the span is not a boundary.

    A cut point's true extent is bounded by its successor, so deriving ``size`` from the next
    cut point makes addressed ranges disjoint *and* a complete partition, absorbing a
    function's interior literal-pool/jump-table holes into the function (where they belong).
    Gap blobs are cut points too, so un-symbolised regions stay separate entries and stop a
    neighbour's growth. The last entry in a block is bounded by the block end (from
    ``block_ends``); without it the draft size is kept.
    """
    per_block: dict[tuple[str, str], list[dict]] = {}
    for e in entries:
        if e["kind"] != "external":
            per_block.setdefault((e["module"], e["block"]), []).append(e)
    changed = 0
    for (_, block), rows in per_block.items():
        rows.sort(key=lambda e: int(e["addr"], 16))
        for e, nxt in zip(rows, rows[1:]):
            size = int(nxt["addr"], 16) - int(e["addr"], 16)
            if size != int(e["size"]):
                e["size"] = str(size)
                changed += 1
        end = block_ends.get(block)
        if end is not None and rows:
            last = rows[-1]
            size = end - int(last["addr"], 16)
            if size >= 0 and size != int(last["size"]):
                last["size"] = str(size)
                changed += 1
    return changed


def sort_entries(entries: list[dict]) -> list[dict]:
    """Addressed rows ascending by address; externals last, by name."""
    addressed = [e for e in entries if e["kind"] != "external"]
    externals = [e for e in entries if e["kind"] == "external"]
    addressed.sort(key=lambda e: (e["module"], int(e["addr"], 16)))
    externals.sort(key=lambda e: (e["module"], e["name"]))
    return addressed + externals


def audit(entries: list[dict]) -> dict:
    """Honesty checks the ledger is expected to satisfy at seed time.

    * exact ``(module, addr)`` duplicates are a hard error (the export promises one row per
      primary symbol; an alias here would need the ``is_alias`` guard);
    * overlapping address ranges within a block are reported (nested/`Data` components are a
      known, not-yet-enumerated follow-up — see architecture.md).
    """
    by_key: dict[tuple[str, str], list[dict]] = {}
    by_name: dict[tuple[str, str], list[dict]] = {}
    for e in entries:
        if e["kind"] == "external":
            by_name.setdefault((e["module"], e["name"]), []).append(e)
        else:
            by_key.setdefault((e["module"], e["addr"]), []).append(e)
    dup_keys = {k: v for k, v in by_key.items() if len(v) > 1}
    dup_names = {k: v for k, v in by_name.items() if len(v) > 1}

    overlaps: list[tuple[str, str, str, str]] = []
    per_block: dict[tuple[str, str], list[dict]] = {}
    for e in entries:
        if e["kind"] != "external":
            per_block.setdefault((e["module"], e["block"]), []).append(e)
    for (module, block), rows in per_block.items():
        rows.sort(key=lambda e: int(e["addr"], 16))
        prev = None
        for e in rows:
            start = int(e["addr"], 16)
            if prev is not None:
                prev_start, prev_size = prev
                if start < prev_start + prev_size:
                    overlaps.append((module, block, f"{prev_start:08x}", e["addr"]))
            prev = (start, int(e["size"]))
    return {"dup_keys": dup_keys, "dup_names": dup_names, "overlaps": overlaps}


def serialize(entries: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(
        buf, fieldnames=LEDGER_COLUMNS, delimiter="\t", lineterminator="\n",
        extrasaction="ignore",
    )
    w.writeheader()
    w.writerows(entries)
    return buf.getvalue()


def report(entries: list[dict], stats: dict, audit_result: dict, out: Path) -> str:
    counted = sum(1 for e in entries if e["kind"] != "external")
    functions = sum(1 for e in entries if e["kind"] == "function")
    data = sum(1 for e in entries if e["kind"] == "data")
    lines = [
        f"ledger: {out}",
        f"  rows              {len(entries)}",
        f"  counted (non-ext) {counted}   [functions {functions}, data {data}]",
        f"  cut points        {stats['content_cut']}",
        f"  gap blobs         {stats['gaps']}",
        f"  externals         {stats['externals']}  (excluded from denominator)",
        f"  metadata skipped  {stats['metadata_skipped']}",
        f"  duplicate (module,addr): {len(audit_result['dup_keys'])}",
        f"  duplicate external name:  {len(audit_result['dup_names'])}",
        f"  overlapping ranges (draft): {len(audit_result['overlaps'])}",
        f"  sizes partitioned:        {stats['partitioned']}",
        f"  block ends applied:       {stats['blocks']}",
        f"  block heads filled:       {stats.get('heads_filled', 0)}",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--in-dir", type=Path, default=DEFAULT_IN_DIR, help="inventory export directory")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="committed ledger path")
    ap.add_argument("--module", default="main", help="module name (single-module seed: main)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing ledger (deliberate re-seed; the ledger is hand-owned)")
    args = ap.parse_args(argv)

    for name in ("inventory.tsv", "inventory.gaps.tsv", "inventory.externals.tsv"):
        if not (args.in_dir / name).exists():
            print(f"error: missing {args.in_dir / name}", file=sys.stderr)
            print("run tools/ghidra/inventory.sh first", file=sys.stderr)
            return 2

    entries, stats = build_entries(args.in_dir, args.module)
    extents = read_block_extents(args.in_dir)
    stats["blocks"] = "yes" if extents else "no (draft sizes)"
    if not extents:
        print("warning: inventory.blocks.tsv missing — block heads/tails unbounded; "
              "rerun tools/ghidra/inventory.sh", file=sys.stderr)
    stats["heads_filled"] = fill_block_heads(entries, extents, args.module)
    entries = sort_entries(entries)
    stats["partitioned"] = partition_sizes(entries, {b: e for b, (_s, e) in extents.items()})
    audit_result = audit(entries)

    print(report(entries, stats, audit_result, args.out))

    if audit_result["dup_keys"]:
        print("error: duplicate (module,addr) entries — alias handling required:", file=sys.stderr)
        for (module, addr) in list(audit_result["dup_keys"])[:10]:
            print(f"  {module} {addr}", file=sys.stderr)
        return 1

    if args.out.exists() and not args.force:
        print(f"error: {args.out} already exists — the ledger is hand-owned and carries "
              "authored status; pass --force to overwrite it deliberately", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(serialize(entries))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
